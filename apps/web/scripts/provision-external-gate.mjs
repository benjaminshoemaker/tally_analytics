import crypto from 'node:crypto';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import dotenv from 'dotenv';
import pg from 'pg';
import Stripe from 'stripe';

const { Client } = pg;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(__dirname, '..');
const repoRoot = path.resolve(appDir, '..', '..');
const summaryPath = path.join(repoRoot, 'tmp', 'external-gate-provision', 'summary.json');
const rootEnvPath = path.join(repoRoot, '.env.local');
const stripeApiVersion = '2025-12-15.clover';

const generatedEnvKeys = [
  'TALLY_HOSTED_PROJECT_ID',
  'TALLY_HOSTED_MCP_ACCESS_TOKEN',
  'STRIPE_PRICE_PRO',
  'STRIPE_PRICE_TEAM',
  'STRIPE_BILLING_PORTAL_CONFIG_ID',
];

function loadEnv() {
  for (const candidate of [
    path.join(appDir, '.env.local'),
    path.join(appDir, '.env'),
    rootEnvPath,
    path.join(repoRoot, '.env'),
  ]) {
    if (fs.existsSync(candidate)) dotenv.config({ path: candidate, override: false });
  }
}

function requireEnv(name) {
  const value = process.env[name];
  if (typeof value !== 'string' || value.trim().length === 0) {
    throw new Error(`Missing required environment variable: ${name}`);
  }
  return value.trim();
}

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function writeJson(filePath, value) {
  ensureDir(filePath);
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

function appendOrReplaceEnv(filePath, values) {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
  const lines = existing.split(/\r?\n/);
  const pending = new Map(Object.entries(values));
  const nextLines = lines.map((line) => {
    const match = /^([A-Z0-9_]+)=/.exec(line);
    if (!match || !pending.has(match[1])) return line;
    const value = pending.get(match[1]);
    pending.delete(match[1]);
    return `${match[1]}=${value}`;
  });

  if (pending.size > 0) {
    if (nextLines.length && nextLines[nextLines.length - 1] !== '') nextLines.push('');
    nextLines.push('# Generated by pnpm --filter web e2e:provision-external');
    for (const [key, value] of pending) nextLines.push(`${key}=${value}`);
  }

  while (nextLines.length > 1 && nextLines[nextLines.length - 1] === '' && nextLines[nextLines.length - 2] === '') {
    nextLines.pop();
  }

  fs.writeFileSync(filePath, `${nextLines.join('\n').replace(/\n+$/, '')}\n`);
}

function generateOpaqueToken(bytes = 32) {
  return crypto.randomBytes(bytes).toString('base64url');
}

function hashSecret(value) {
  return crypto.createHash('sha256').update(value).digest('hex');
}

function createProjectId() {
  return `proj_${crypto.randomBytes(12).toString('base64url').slice(0, 15)}`;
}

function hostedResourceUrl(appUrl) {
  return `${appUrl.replace(/\/+$/, '')}/api/mcp`;
}

function smokeFingerprint() {
  return crypto
    .createHash('sha256')
    .update(JSON.stringify({ source: 'mcp_codex', identity: 'external_gate', name: 'hosted-smoke' }))
    .digest('hex');
}

async function provisionHosted() {
  const databaseUrl = requireEnv('TALLY_HOSTED_DATABASE_URL');
  const appUrl = (process.env.TALLY_HOSTED_APP_URL ?? 'https://usetally.xyz').replace(/\/+$/, '');
  const email = (process.env.TALLY_HOSTED_SMOKE_EMAIL ?? 'e2e+hosted-smoke@usetally.xyz').toLowerCase();
  const resource = hostedResourceUrl(appUrl);
  const now = new Date();
  const accessToken = generateOpaqueToken(32);
  const refreshToken = generateOpaqueToken(32);
  const accessExpiresAt = new Date(now.getTime() + 60 * 60 * 1000);
  const refreshExpiresAt = new Date(now.getTime() + 30 * 24 * 60 * 60 * 1000);
  const clientId = 'mcp_tally_external_gate';
  const fingerprint = smokeFingerprint();
  const client = new Client({ connectionString: databaseUrl });

  await client.connect();
  try {
    await client.query('BEGIN');
    const userResult = await client.query(
      `
        INSERT INTO users (email, created_at, updated_at)
        VALUES ($1, $2, $2)
        ON CONFLICT (email) DO UPDATE SET updated_at = EXCLUDED.updated_at
        RETURNING id
      `,
      [email, now],
    );
    const userId = userResult.rows[0].id;

    const existingProject = await client.query(
      'SELECT id FROM projects WHERE user_id = $1 AND mcp_fingerprint = $2 LIMIT 1',
      [userId, fingerprint],
    );
    const projectId = existingProject.rows[0]?.id ?? createProjectId();
    if (existingProject.rows[0]?.id) {
      await client.query(
        `
          UPDATE projects
          SET status = 'active',
              display_name = 'Tally External Smoke',
              source = 'mcp_codex',
              detected_analytics = ARRAY['tally']::text[],
              updated_at = $3
          WHERE id = $1 AND user_id = $2
        `,
        [projectId, userId, now],
      );
    } else {
      await client.query(
        `
          INSERT INTO projects (
            id,
            user_id,
            source,
            display_name,
            status,
            detected_analytics,
            mcp_repo_name,
            mcp_app_root,
            mcp_framework,
            mcp_package_manager,
            mcp_fingerprint,
            created_at,
            updated_at
          )
          VALUES ($1, $2, 'mcp_codex', 'Tally External Smoke', 'active', ARRAY['tally']::text[], 'tally-external-smoke', '.', 'nextjs', 'pnpm', $3, $4, $4)
        `,
        [projectId, userId, fingerprint, now],
      );
    }

    await client.query(
      `
        INSERT INTO oauth_clients (
          client_id,
          client_name,
          redirect_uris,
          grant_types,
          response_types,
          scope,
          created_at,
          updated_at
        )
        VALUES ($1, 'Tally external gate', $2, $3, $4, 'mcp:tasks', $5, $5)
        ON CONFLICT (client_id) DO UPDATE
        SET client_name = EXCLUDED.client_name,
            redirect_uris = EXCLUDED.redirect_uris,
            grant_types = EXCLUDED.grant_types,
            response_types = EXCLUDED.response_types,
            scope = EXCLUDED.scope,
            updated_at = EXCLUDED.updated_at
      `,
      [clientId, ['http://localhost:17777/oauth/callback'], ['authorization_code', 'refresh_token'], ['code'], now],
    );

    await client.query(
      'UPDATE oauth_access_tokens SET revoked_at = $1 WHERE client_id = $2 AND user_id = $3 AND resource = $4 AND revoked_at IS NULL',
      [now, clientId, userId, resource],
    );
    await client.query(
      'UPDATE oauth_refresh_tokens SET revoked_at = $1 WHERE client_id = $2 AND user_id = $3 AND resource = $4 AND revoked_at IS NULL',
      [now, clientId, userId, resource],
    );
    await client.query(
      `
        INSERT INTO oauth_access_tokens (
          token_hash,
          client_id,
          user_id,
          scope,
          resource,
          expires_at,
          created_at
        )
        VALUES ($1, $2, $3, 'mcp:tasks', $4, $5, $6)
      `,
      [hashSecret(accessToken), clientId, userId, resource, accessExpiresAt, now],
    );
    await client.query(
      `
        INSERT INTO oauth_refresh_tokens (
          token_hash,
          client_id,
          user_id,
          scope,
          resource,
          expires_at,
          created_at
        )
        VALUES ($1, $2, $3, 'mcp:tasks', $4, $5, $6)
      `,
      [hashSecret(refreshToken), clientId, userId, resource, refreshExpiresAt, now],
    );
    await client.query('COMMIT');

    return {
      projectId,
      userEmail: email,
      appUrl,
      resource,
      accessToken,
      accessTokenExpiresAt: accessExpiresAt.toISOString(),
    };
  } catch (error) {
    await client.query('ROLLBACK').catch(() => undefined);
    throw error;
  } finally {
    await client.end();
  }
}

async function listAll(fetchPage) {
  const values = [];
  let startingAfter = undefined;
  for (;;) {
    const page = await fetchPage(startingAfter);
    values.push(...page.data);
    if (!page.has_more || page.data.length === 0) break;
    startingAfter = page.data[page.data.length - 1].id;
  }
  return values;
}

async function getOrCreateProduct(stripe, plan) {
  const products = await listAll((startingAfter) =>
    stripe.products.list({ active: true, limit: 100, ...(startingAfter ? { starting_after: startingAfter } : {}) }),
  );
  const existing = products.find(
    (product) => product.metadata?.tally_external_gate === 'true' && product.metadata?.tally_plan === plan,
  );
  if (existing) return existing;

  return stripe.products.create({
    name: plan === 'pro' ? 'Tally Pro' : 'Tally Team',
    description: `Tally ${plan} plan for external release gate verification.`,
    metadata: { tally_external_gate: 'true', tally_plan: plan },
  });
}

async function getOrCreatePrice(stripe, product, plan) {
  const lookupKey = `tally_external_gate_${plan}_monthly`;
  const existingPrices = await stripe.prices.list({ lookup_keys: [lookupKey], limit: 1 });
  const existing = existingPrices.data.find((price) => price.active && price.recurring?.interval === 'month');
  if (existing) return existing;

  return stripe.prices.create({
    product: product.id,
    currency: 'usd',
    unit_amount: plan === 'pro' ? 2900 : 9900,
    recurring: { interval: 'month' },
    lookup_key: lookupKey,
    metadata: { tally_external_gate: 'true', tally_plan: plan },
  });
}

function portalFeatures(proProduct, proPrice, teamProduct, teamPrice) {
  return {
    customer_update: { enabled: true, allowed_updates: ['email', 'name', 'address'] },
    invoice_history: { enabled: true },
    payment_method_update: { enabled: true },
    subscription_cancel: { enabled: true, mode: 'at_period_end', proration_behavior: 'none' },
    subscription_update: {
      enabled: true,
      default_allowed_updates: ['price'],
      proration_behavior: 'create_prorations',
      products: [
        { product: proProduct.id, prices: [proPrice.id] },
        { product: teamProduct.id, prices: [teamPrice.id] },
      ],
    },
  };
}

async function getOrCreatePortalConfig(stripe, appUrl, proProduct, proPrice, teamProduct, teamPrice) {
  const configs = await listAll((startingAfter) =>
    stripe.billingPortal.configurations.list({
      active: true,
      limit: 100,
      ...(startingAfter ? { starting_after: startingAfter } : {}),
    }),
  );
  const existing = configs.find((config) => config.metadata?.tally_external_gate === 'true');
  const update = {
    business_profile: {
      headline: 'Manage your Tally subscription.',
      privacy_policy_url: `${appUrl}/privacy`,
    },
    default_return_url: `${appUrl}/settings`,
    features: portalFeatures(proProduct, proPrice, teamProduct, teamPrice),
    metadata: { tally_external_gate: 'true' },
    name: 'Tally external release gate',
  };

  if (existing) return stripe.billingPortal.configurations.update(existing.id, update);
  return stripe.billingPortal.configurations.create(update);
}

async function provisionStripe() {
  const secretKey = requireEnv('STRIPE_SECRET_KEY');
  if (!secretKey.startsWith('sk_test_')) {
    throw new Error('STRIPE_SECRET_KEY must be a Stripe test-mode key for external gate provisioning.');
  }
  const appUrl = (process.env.TALLY_HOSTED_APP_URL ?? 'https://usetally.xyz').replace(/\/+$/, '');
  const stripe = new Stripe(secretKey, { apiVersion: stripeApiVersion });
  const proProduct = await getOrCreateProduct(stripe, 'pro');
  const teamProduct = await getOrCreateProduct(stripe, 'team');
  const proPrice = await getOrCreatePrice(stripe, proProduct, 'pro');
  const teamPrice = await getOrCreatePrice(stripe, teamProduct, 'team');
  const portalConfig = await getOrCreatePortalConfig(stripe, appUrl, proProduct, proPrice, teamProduct, teamPrice);

  return {
    proProductId: proProduct.id,
    teamProductId: teamProduct.id,
    proPriceId: proPrice.id,
    teamPriceId: teamPrice.id,
    billingPortalConfigId: portalConfig.id,
  };
}

function printHelp() {
  console.log('Usage: pnpm --filter web e2e:provision-external');
  console.log('');
  console.log('Requires TALLY_HOSTED_DATABASE_URL and STRIPE_SECRET_KEY=sk_test_...');
  console.log('Creates/reuses a hosted smoke project, a short-lived MCP token, Stripe test prices, and a billing portal config.');
  console.log('Writes generated env values to repo-root .env.local.');
}

async function main() {
  if (process.argv.includes('--help') || process.argv.includes('-h')) {
    printHelp();
    return;
  }
  const unknown = process.argv.slice(2).filter((arg) => arg !== '--');
  if (unknown.length > 0) throw new Error(`Unknown argument: ${unknown.join(' ')}`);

  loadEnv();

  const hosted = await provisionHosted();
  const stripe = await provisionStripe();
  const envValues = {
    TALLY_HOSTED_PROJECT_ID: hosted.projectId,
    TALLY_HOSTED_MCP_ACCESS_TOKEN: hosted.accessToken,
    STRIPE_PRICE_PRO: stripe.proPriceId,
    STRIPE_PRICE_TEAM: stripe.teamPriceId,
    STRIPE_BILLING_PORTAL_CONFIG_ID: stripe.billingPortalConfigId,
  };
  appendOrReplaceEnv(rootEnvPath, envValues);

  const summary = {
    ok: true,
    generatedEnvPath: rootEnvPath,
    generatedEnvKeys,
    hosted: {
      projectId: hosted.projectId,
      userEmail: hosted.userEmail,
      appUrl: hosted.appUrl,
      resource: hosted.resource,
      accessTokenExpiresAt: hosted.accessTokenExpiresAt,
    },
    stripe,
  };
  writeJson(summaryPath, summary);
  console.log(JSON.stringify(summary, null, 2));
}

main().catch((error) => {
  const summary = {
    ok: false,
    error: error instanceof Error ? error.message : String(error),
  };
  writeJson(summaryPath, summary);
  console.error(summary.error);
  process.exitCode = 1;
});
